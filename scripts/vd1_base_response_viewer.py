"""Presentation-only viewer for the no-vision VD1 diagnostic.

The viewer owns a copy of the model and separate data. Its UI, mouse forces,
camera tracking and evaluation labels can never modify the controlled model,
sensor buffer, actuator targets or actor observations.
"""
from __future__ import annotations

import copy
import math
import threading
import time

import numpy as np


def telemetry_labels(sim_time, base_command, body_velocity, tilt, paused=False):
    """Read-only evaluation display, not a source of controller feedback."""
    return (
        'VD1 NO VISION | ' + ('PAUSED: SPACE to start/resume' if paused else 'RUNNING: SPACE to pause'),
        't=%.2fs | command vx=%.3f m/s, w=%.3f rad/s' %
        (sim_time, base_command[0], base_command[2]),
        'EVAL actual vx=%.3f, vy=%.3f m/s | tilt=%.2f deg' %
        (body_velocity[0], body_velocity[1], tilt),
        'Fixed BASE-frame TCP target | no camera or heading feedback',
    )


class DiagnosticViewer:
    """Passive rendering of copied physics state, with wall-time pacing only."""

    def __init__(self, model, data, start_paused=False, realtime_factor=1.):
        if not math.isfinite(realtime_factor) or not 0 < realtime_factor <= 4:
            raise ValueError('realtime_factor must be finite and in (0,4]')
        import mujoco
        import mujoco.viewer
        self.model = copy.copy(model)
        self.data = mujoco.MjData(self.model)
        self._copy_state(data)
        self.base = self.model.body('base_link').id
        self.realtime_factor = float(realtime_factor)
        self.paused = threading.Event()
        if start_paused:
            self.paused.set()
        self.handle = mujoco.viewer.launch_passive(
            self.model, self.data, key_callback=self._key,
            show_left_ui=False, show_right_ui=False)
        with self.handle.lock():
            self.handle.cam.distance = 3.8
            self.handle.cam.azimuth = 135
            self.handle.cam.elevation = -22
            self.handle.opt.geomgroup[3] = 0
            self.handle.opt.label = mujoco.mjtLabel.mjLABEL_SELECTION

    def _key(self, keycode):
        if keycode == 32:  # SPACE; MuJoCo's passive viewer does not step physics.
            if self.paused.is_set():
                self.paused.clear()
            else:
                self.paused.set()

    def _copy_state(self, source):
        import mujoco
        self.data.time = float(source.time)
        self.data.qpos[:] = source.qpos
        self.data.qvel[:] = source.qvel
        self.data.act[:] = source.act
        self.data.ctrl[:] = source.ctrl
        self.data.mocap_pos[:] = source.mocap_pos
        self.data.mocap_quat[:] = source.mocap_quat
        # Ignore all forces generated by interaction with the display model.
        self.data.qfrc_applied[:] = 0
        self.data.xfrc_applied[:] = 0
        mujoco.mj_forward(self.model, self.data)

    def is_running(self):
        return self.handle.is_running()

    def update(self, source, command, evaluation=None):
        import mujoco
        if not self.is_running():
            return
        if evaluation is None:
            velocity, tilt = (0., 0., 0.), 0.
        else:
            velocity, tilt = evaluation['body_velocity_b'], evaluation['tilt_deg']
        labels = telemetry_labels(source.time, command, velocity, tilt, self.paused.is_set())
        with self.handle.lock():
            self._copy_state(source)
            base_position = self.data.xpos[self.base].copy()
            self.handle.cam.lookat[:] = base_position + (-.35, 0., -.08)
            scene = self.handle.user_scn
            if scene is not None:
                scene.ngeom = len(labels)
                for index, label in enumerate(labels):
                    geom = scene.geoms[index]
                    mujoco.mjv_initGeom(geom, mujoco.mjtGeom.mjGEOM_LABEL,
                                       np.zeros(3), base_position + (-.3, 0., 1.05-index*.14),
                                       np.eye(3).reshape(-1), np.array([1., 1., 1., 1.], dtype=np.float32))
                    geom.label = label
                # A one-metre grid in the DISPLAY scene makes travel visible
                # despite the following camera. No collision/model is added.
                center_x, center_y = np.floor(base_position[:2]).astype(int)
                for offset in range(-5, 7):
                    for axis in (0, 1):
                        start = np.array([center_x-5., center_y-5., .002])
                        end = np.array([center_x+6., center_y+6., .002])
                        start[axis] = end[axis] = (center_x if axis == 0 else center_y) + offset
                        geom = scene.geoms[scene.ngeom]
                        mujoco.mjv_initGeom(geom, mujoco.mjtGeom.mjGEOM_LINE,
                                           np.zeros(3), np.zeros(3), np.eye(3).reshape(-1),
                                           np.array([.65, .65, .65, 1.], dtype=np.float32))
                        mujoco.mjv_connector(geom, mujoco.mjtGeom.mjGEOM_LINE, 1., start, end)
                        scene.ngeom += 1
        self.handle.sync()

    def wait_until_running(self, source, command, evaluation, stopped):
        while self.is_running() and self.paused.is_set() and not stopped[0]:
            self.update(source, command, evaluation)
            time.sleep(.02)
        return self.is_running() and not stopped[0]

    def pace(self, started_at, actor_dt, stopped):
        deadline = started_at + actor_dt / self.realtime_factor
        while self.is_running() and not stopped[0]:
            remaining = deadline - time.monotonic()
            if remaining <= 0:
                break
            time.sleep(min(remaining, .02))

    def close(self):
        self.handle.close()
